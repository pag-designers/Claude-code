// Embeds prisma/migrations/*/migration.sql into a TS module so the packaged app can migrate
// without the Prisma CLI or any file lookup (ADR-004).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'prisma', 'migrations');
const names = fs
  .readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();
const entries = names.map((name) => ({
  name,
  sql: fs.readFileSync(path.join(dir, name, 'migration.sql'), 'utf8'),
}));
const out = `// AUTO-GENERATED by scripts/gen-migrations.mjs — do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(entries, null, 2)};\n`;
fs.mkdirSync(path.join(root, 'electron/main/db'), { recursive: true });
fs.writeFileSync(path.join(root, 'electron/main/db/migrations.generated.ts'), out);
console.log(`Embedded ${entries.length} migration(s): ${names.join(', ')}`);
