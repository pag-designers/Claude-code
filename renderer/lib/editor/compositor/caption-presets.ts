const BUILTINS: CaptionStyle[] = BUILTIN_STYLE_IDS.map((id) => captionStyleSchema.parse(RAW[id]));

/** Fresh copies of the 14 presets, in the brief's order. */
export const builtinCaptionStyles = (): CaptionStyle[] => BUILTINS.map((s) => structuredClone(s));

/** Style for a subtitle item: its override, else a custom/built-in preset by id, else Clean Pop. */
export function resolveCaptionStyle(
  styleId: string,
  override: CaptionStyle | null,
  custom: readonly CaptionStyle[] = [],
): CaptionStyle {
  if (override) return override;
  return (
    custom.find((s) => s.id === styleId) ??
    BUILTINS.find((s) => s.id === styleId) ??
    (BUILTINS.find((s) => s.id === DEFAULT_STYLE_ID) as CaptionStyle)
  );
}
